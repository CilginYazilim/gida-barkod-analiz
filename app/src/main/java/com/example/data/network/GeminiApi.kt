    suspend fun chatAboutProduct(productName: String, ingredients: String, question: String, chatHistory: List<Pair<String, Boolean>>): String = withContext(Dispatchers.IO) {
        if (apiKey.isEmpty() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext "Yapay zekâ sohbeti şu anda demo modunda çalışıyor. Ürün: $productName hakkında soru sordunuz: '$question'. Bu ürün yüksek oranda katkı veya şeker içeriyor olabilir, dengeli tüketilmesi önerilir."
        }

        val historyPrompt = chatHistory.joinToString("\n") { (msg, isUser) ->
            if (isUser) "Kullanıcı: $msg" else "Yapay Zeka: $msg"
        }

        val prompt = """
            Ürün Adı: $productName
            İçindekiler: $ingredients
            
            Önceki Görüşme Geçmişi:
            $historyPrompt
            
            Kullanıcı Sorusu: $question
            
            Lütfen yukarıdaki ürün bilgilerini ve içerikleri dikkate alarak kullanıcının sorusuna samimi, bilimsel temelli ve kolay anlaşılır bir Türkçe yanıt ver. Maksimum 3-4 cümle olsun.
        """.trimIndent()

        val request = GeminiGenerateRequest(
            contents = listOf(
                GeminiContent(parts = listOf(GeminiPart(text = prompt)))
            )
        )

        try {
            val response = GeminiRetrofitClient.service.generateContent(apiKey, request)
            response.candidates?.firstOrNull()?.content?.parts?.firstOrNull()?.text ?: "Cevap üretilemedi."
        } catch (e: Exception) {
            "Sohbet hatası oluştu: ${e.message}"
        }
    }

