            isHalal = true,
            halalStatusExplanation = halalExplanation
        )
    }

    private fun getMockComparison(product1: SavedProduct, product2: SavedProduct): GeminiComparison {
        val path1 = product1.healthScore > product2.healthScore
        val winner = if (path1) product1 else product2
        val loser = if (path1) product2 else product1
        
        return GeminiComparison(
            product1Name = product1.name,
            product2Name = product2.name,
            product1Score = product1.healthScore,
            product2Score = product2.healthScore,
            comparisonDetails = "Analiz sonucunda, ${winner.name} ürünü ${winner.healthScore} puanı ile ${loser.name} (${loser.healthScore} puan) ürününe kıyasla daha dengeli bir besin içeriğine sahiptir. ${loser.name}, içeriğinde bulunan katkı maddeleri veya yüksek şeker/yağ sebebiyle daha düşük bir skor almıştır.",
            healthierOption = winner.name,
            directRecommendation = "${winner.name} ürününü tercih etmek, vücudunuz için çok daha sağlıklı ve katkısız bir alternatif olacaktır."
        )
    }
