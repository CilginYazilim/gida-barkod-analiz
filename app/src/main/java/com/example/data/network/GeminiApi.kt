    private fun getMockAnalysisForBarcode(barcode: String, offProduct: OFFProduct? = null): GeminiProductAnalysis {
        // Explicit checks for user's specific barcodes
        val isKetchupBarcode = barcode == "8699118044680"
        val isNarEksisiBarcode = barcode == "8681749145348"

        val prodName = when {
            isKetchupBarcode -> "Domates Ketçabı"
            isNarEksisiBarcode -> "Nar Ekşisi"
            offProduct != null -> offProduct.productName ?: offProduct.productNameTr ?: "Bilinmeyen Ürün"
            barcode.endsWith("1") || barcode.endsWith("3") || barcode.endsWith("5") || barcode.startsWith("8690") -> "Çikolatalı Gofret"
            else -> "Sade Soda"
        }

        val prodBrand = when {
            isKetchupBarcode -> "Çokça"
            isNarEksisiBarcode -> "Tarım Kredi Kooperatifi"
            offProduct != null -> offProduct.brands ?: "Bilinmeyen Marka"
            barcode.endsWith("1") || barcode.endsWith("3") || barcode.endsWith("5") || barcode.startsWith("8690") -> "Ülker"
            else -> "Beypazarı"
        }

        val prodCategory = when {
            isKetchupBarcode -> "Ketçap"
            isNarEksisiBarcode -> "Sos"
            offProduct != null -> offProduct.categories ?: "Gıda"
            barcode.endsWith("1") || barcode.endsWith("3") || barcode.endsWith("5") || barcode.startsWith("8690") -> "Atıştırmalık"
            else -> "İçecek"
        }

        val prodGrammage = when {
            isKetchupBarcode -> "650g"
            isNarEksisiBarcode -> "350g"
