            isVegetarian = true,
            isGlutenFree = isSodaOrWater || isPomegranate,
            isLactoseFree = isSodaOrWater || isPomegranate || !isSweet,
            isSuitableForChildren = isSodaOrWater || isPomegranate || !isSweet,
            isSuitableForDiabetics = isSodaOrWater || (!isSweet && !isKetchup),
            aiVerdict = when {
                isPomegranate -> "Sindirime yardımcı olan, zengin antioksidan içeriğiyle kalbi koruyan son derece yararlı ve doğal bir sostur."
                isKetchup -> "İçerdiği likopen sebebiyle faydalı olsa da, şeker oranı yüksek olduğundan ölçülü tüketilmelidir."
