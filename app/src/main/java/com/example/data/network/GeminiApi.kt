            isSweet -> "Şeker, Buğday Unu, Bitkisel Yağ (Palm), Kakao Kitlesi, Süt Tozu, Peyniraltı Suyu Tozu, Emülgatör (Soya Lesitini - E322), Kabartıcılar (E500, E503), Yapay Tatlandırıcı (E951)"
            else -> "Su, Tuz, Maya, Un, Koruyucu (E202), Asitlik Düzenleyici (Sitrik Asit - E330)"
        }

        val nutrition = when {
            isKetchup -> "Sugar: 16.0g, Fat: 0.1g, Protein: 1.1g, Carbohydrates: 23.0g, Energy: 97kcal, Salt: 1.2g, Fiber: 0.4g"
            isPomegranate -> "Sugar: 50g, Fat: 0g, Protein: 1.2g, Carbohydrates: 64g, Energy: 267kcal, Salt: 0g, Fiber: 0g"
            isSodaOrWater -> "Sugar: 0g, Fat: 0g, Protein: 0g, Carbohydrates: 0g, Energy: 0kcal"
            isSweet -> "Sugar: 36g, Fat: 22g, Protein: 5g, Carbohydrates: 58g, Energy: 512kcal"
