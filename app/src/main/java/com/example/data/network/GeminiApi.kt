            name = prodName,
            brand = prodBrand,
            category = prodCategory,
            ingredients = ingredients,
            nutritionFacts = nutrition,
            healthScore = score,
            healthExplanation = explanation,
            sugarScore = when { isSweet -> 30; isKetchup -> 55; isPomegranate -> 45; else -> 85 },
