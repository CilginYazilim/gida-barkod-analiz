// --- Gemini Request / Response Models ---

@JsonClass(generateAdapter = true)
data class GeminiBlob(
    val mimeType: String,
    val data: String // Base64 chunk
)

@JsonClass(generateAdapter = true)
data class GeminiPart(
    val text: String? = null,
    val inlineData: GeminiBlob? = null
)

@JsonClass(generateAdapter = true)
data class GeminiContent(
    val parts: List<GeminiPart>
)

@JsonClass(generateAdapter = true)
data class GeminiGenerateRequest(
    val contents: List<GeminiContent>,
    val systemInstruction: GeminiContent? = null
)

@JsonClass(generateAdapter = true)
data class GeminiCandidate(
    val content: GeminiContent? = null
)

@JsonClass(generateAdapter = true)
data class GeminiGenerateResponse(
    val candidates: List<GeminiCandidate>? = null
)

// --- Domain Models Generated by Gemini ---

@JsonClass(generateAdapter = true)
data class GeminiAdditive(
    val code: String,       // e.g. "E150d"
    val category: String,   // e.g. "Renklendirici"
    val name: String,       // e.g. "Karamel Amonyum Sülfit"
    val risk: String,       // "Düşük", "Orta", "Yüksek"
    val description: String, // Turkish explanation
    val whoShouldAvoid: String // Phenylketonurics, children, etc.
)

/** Yapısal besin değerleri (100g/100ml için); bilinmeyen alan null = "Belirsiz". */
@JsonClass(generateAdapter = true)
data class NutritionValues(
    val energy: Double? = null,   // kcal
    val sugar: Double? = null,    // g
    val fat: Double? = null,      // g
    val satFat: Double? = null,   // g (doymuş yağ)
    val salt: Double? = null,     // g
    val protein: Double? = null,  // g
    val carb: Double? = null,     // g
    val fiber: Double? = null     // g
)

@JsonClass(generateAdapter = true)
data class GeminiProductAnalysis(
    val name: String,
    val brand: String,
    val category: String,
    val ingredients: String,
    val nutritionFacts: String, // Sugar: Xg, Fat: Yg etc. (insan-okur özet)
    val nutrition: NutritionValues? = null, // Yapısal besin (skor hesabı için)
    val healthScore: Int,
    val healthExplanation: String,
    val sugarScore: Int = 0,        // Şeker riski puanı 0-100 (yüksek=az şeker)
    val additiveScore: Int = 0,     // Katkı maddesi yoğunluk puanı 0-100 (yüksek=az katkı)
    val nutritionScore: Int = 0,    // Besin kalitesi puanı 0-100
    val scoreTags: List<String> = emptyList(), // "Protein yüksek", "Palm yağı var" vb.
    val allergens: List<String> = emptyList(),  // "Gluten", "Süt", "Yumurta" ...
    val eCodesList: List<GeminiAdditive> = emptyList(),
    val isVegan: Boolean = false,
    val isVegetarian: Boolean = false,
    val isGlutenFree: Boolean = false,
    val isLactoseFree: Boolean = false,
    val isSuitableForChildren: Boolean = false,
    val isSuitableForDiabetics: Boolean = false,
    val aiVerdict: String, // Detailed Turkish commentary
    val grammage: String = "",
    // 4 durumlu helal: "muhtemel_helal" | "supheli" | "helal_degil" (AI "sertifikali" ÜRETMEZ)
    val halalStatus: String = "supheli",
    val isHalal: Boolean = false, // geriye uyumluluk (halalStatus'tan türetilir)
    val halalStatusExplanation: String = "Bu ürünün doğrulanmış bir helal sertifikası bilgisi bulunmamaktadır; içeriğine göre kesin hüküm verilemez."
)

@JsonClass(generateAdapter = true)
data class GeminiComparison(
    val product1Name: String,
    val product2Name: String,
    val product1Score: Int,
    val product2Score: Int,
    val comparisonDetails: String, // Turkish detailed text comparing ingredients and nutrition
    val healthierOption: String, // Name of the healthier product
    val directRecommendation: String // Direct visual reasoning in Turkish
)

interface GeminiService {
    @POST("v1beta/models/gemini-3.5-flash:generateContent")
    suspend fun generateContent(
        @Query("key") apiKey: String,
        @Body request: GeminiGenerateRequest
    ): GeminiGenerateResponse
}

object GeminiRetrofitClient {
    private const val BASE_URL = "https://generativelanguage.googleapis.com/"

    private val okHttpClient = OkHttpClient.Builder()
         .connectTimeout(15, TimeUnit.SECONDS)
         .readTimeout(15, TimeUnit.SECONDS)
         .writeTimeout(15, TimeUnit.SECONDS)
         .build()

    val moshi: Moshi = Moshi.Builder()
        .addLast(KotlinJsonAdapterFactory())
        .build()

    val service: GeminiService by lazy {
        Retrofit.Builder()
            .baseUrl(BASE_URL)
            .client(okHttpClient)
            .addConverterFactory(MoshiConverterFactory.create(moshi))
            .build()
            .create(GeminiService::class.java)
    }
}

